const deny = (reason) => ({ decision: "deny", reason });
const ask = (reason) => ({ decision: "ask", reason });

const GIT_VALUE_OPTIONS = new Set([
  "-c",
  "-C",
  "--git-dir",
  "--work-tree",
  "--namespace",
  "--config-env",
]);
const CONFIG_VALUE_FLAGS = new Set([
  "-f",
  "--file",
  "--blob",
  "--type",
  "--default",
  "--comment",
  "--value",
]);
const CONFIG_WRITE_FLAGS = new Set(["--unset", "--unset-all", "--add", "--replace-all"]);
const CONFIG_READ_FLAGS = new Set([
  "--get",
  "--get-all",
  "--get-regexp",
  "--get-urlmatch",
  "--get-color",
  "--get-colorbool",
  "-l",
  "--list",
]);
const PUSH_VALUE_FLAGS = new Set(["-o", "--push-option", "--repo", "--receive-pack", "--exec"]);
const CHECKOUT_VALUE_FLAGS = new Set(["-b", "-B", "--orphan"]);
const SWITCH_VALUE_FLAGS = new Set(["-c", "-C", "--create", "--force-create", "--orphan"]);
const RESTORE_VALUE_FLAGS = new Set(["-s", "--source"]);
const CLEAN_VALUE_FLAGS = new Set(["-e", "--exclude"]);
const STASH_VALUE_FLAGS = new Set(["-m", "--message"]);
const NO_VALUE_FLAGS = new Set();
const PATHSPEC_GLOB = /[*?[]/;
const PACKAGE_INSTALLS = new Set(["add", "install", "i", "remove", "rm"]);
const DOWNLOADED_TOOLS = new Set(["oxlint", "oxfmt", "vitest", "eslint", "prettier"]);

function parseArgs(args, valueFlags) {
  const flags = [];
  const operands = [];
  for (let index = 0; index < args.length; index++) {
    const word = args[index];
    if (!word.quoted && word.text === "--") {
      return { flags, operands, afterDashes: args.slice(index + 1) };
    }
    if (!isFlag(word)) {
      operands.push(word);
      continue;
    }
    flags.push(word.text);
    if (valueFlags.has(word.text)) index++;
  }
  return { flags, operands, afterDashes: null };
}

function shortLetters(flag, valueLetters) {
  if (flag.startsWith("--")) return "";
  const letters = flag.slice(1);
  const valueAt = [...letters].findIndex((letter) => valueLetters.includes(letter));
  return valueAt === -1 ? letters : letters.slice(0, valueAt + 1);
}

function hasShort(flags, letter, valueLetters = "") {
  return flags.some((flag) => shortLetters(flag, valueLetters).includes(letter));
}

function isWithin(path, base) {
  const fromBase = relative(base, path);
  return (
    fromBase === "" ||
    (fromBase !== ".." && !fromBase.startsWith(`..${sep}`) && !isAbsolute(fromBase))
  );
}

function isHooksPathSetting(setting) {
  return setting?.split("=")[0].toLowerCase() === "core.hookspath";
}

function disablesHooks({ name, value }) {
  if (/^GIT_CONFIG_KEY_\d+$/i.test(name)) return isHooksPathSetting(value);
  return /^(?:HUSKY|VITE_GIT_HOOKS)$/i.test(name) && value === "0";
}

function gitInvocation(args, cwd) {
  const settings = [];
  const directories = [];
  let index = 0;
  while (index < args.length && isFlag(args[index])) {
    const option = args[index].text;
    const value = args[index + 1]?.text ?? "";
    if (option === "-c" || option === "--config-env") settings.push(value);
    if (option.startsWith("--config-env=")) settings.push(option.slice("--config-env=".length));
    if (option === "-C") directories.push(value);
    index += GIT_VALUE_OPTIONS.has(option) ? 2 : 1;
  }
  return {
    settings,
    cwd: resolve(cwd, ...directories),
    subcommand: args[index]?.text,
    rest: args.slice(index + 1),
  };
}

function isNoVerify(flag) {
  return flag.length >= "--no-veri".length && "--no-verify".startsWith(flag);
}

function noVerifyVerdict(subcommand, args) {
  const { flags } = parseArgs(args, NO_VALUE_FLAGS);
  if (!flags.some(isNoVerify)) return null;
  return deny(subcommand === "push" ? reasons.pushBypass : reasons.commitBypass);
}

function commitVerdict(args) {
  const { flags } = parseArgs(args, NO_VALUE_FLAGS);
  return hasShort(flags, "n", "mFCctuS") ? deny(reasons.commitBypass) : null;
}

function writesHooksPath(args) {
  const { flags, operands } = parseArgs(args, CONFIG_VALUE_FLAGS);
  const [first, second] = operands.map((word) => word.text);
  if (first === "set" || first === "unset") return isHooksPathSetting(second);
  if (!isHooksPathSetting(first)) return false;
  if (flags.some((flag) => CONFIG_WRITE_FLAGS.has(flag))) return true;
  return second !== undefined && !flags.some((flag) => CONFIG_READ_FLAGS.has(flag));
}

function configVerdict(args) {
  return writesHooksPath(args) ? deny(reasons.hooksDisabled) : null;
}

function pushVerdict(args) {
  const { flags, operands, afterDashes } = parseArgs(args, PUSH_VALUE_FLAGS);
  const refspecs = [...operands, ...(afterDashes ?? [])];
  const forced =
    flags.includes("--force") ||
    hasShort(flags, "f", "o") ||
    refspecs.some((word) => word.text.startsWith("+"));
  return forced ? ask(reasons.forcePush) : null;
}

function resetVerdict(args) {
  return parseArgs(args, NO_VALUE_FLAGS).flags.includes("--hard")
    ? ask(reasons.discardsWork)
    : null;
}

function cleanVerdict(args) {
  const { flags } = parseArgs(args, CLEAN_VALUE_FLAGS);
  const forced = flags.includes("--force") || hasShort(flags, "f", "e");
  const dryRun = flags.includes("--dry-run") || hasShort(flags, "n", "e");
  return forced && !dryRun ? ask(reasons.discardsWork) : null;
}

function namesPath(word, cwd) {
  return word.text === "." || PATHSPEC_GLOB.test(word.text) || existsSync(resolve(cwd, word.text));
}

function checkoutVerdict(args, cwd) {
  const { flags, operands, afterDashes } = parseArgs(args, CHECKOUT_VALUE_FLAGS);
  const forced = flags.includes("--force") || hasShort(flags, "f", "bB");
  const touchesPaths =
    afterDashes === null ? operands.some((word) => namesPath(word, cwd)) : afterDashes.length > 0;
  return forced || touchesPaths ? ask(reasons.discardsWork) : null;
}

function switchVerdict(args) {
  const { flags } = parseArgs(args, SWITCH_VALUE_FLAGS);
  const discards =
    flags.includes("--force") || flags.includes("--discard-changes") || hasShort(flags, "f", "cC");
  return discards ? ask(reasons.discardsWork) : null;
}

function restoreVerdict(args) {
  const { flags } = parseArgs(args, RESTORE_VALUE_FLAGS);
  const staged = flags.includes("--staged") || hasShort(flags, "S", "s");
  const worktree = flags.includes("--worktree") || hasShort(flags, "W", "s");
  return staged && !worktree ? null : ask(reasons.discardsWork);
}

function stashVerdict(args) {
  const action = parseArgs(args, STASH_VALUE_FLAGS).operands[0]?.text;
  return action === "drop" || action === "clear" ? ask(reasons.discardsWork) : null;
}

const gitSubcommands = new Map([
  ["commit", commitVerdict],
  ["config", configVerdict],
  ["push", pushVerdict],
  ["reset", resetVerdict],
  ["clean", cleanVerdict],
  ["checkout", checkoutVerdict],
  ["switch", switchVerdict],
  ["restore", restoreVerdict],
  ["stash", stashVerdict],
]);

function gitVerdict(args, { cwd }) {
  const git = gitInvocation(args, cwd);
  if (git.settings.some(isHooksPathSetting)) return deny(reasons.hooksDisabled);
  const bypass = noVerifyVerdict(git.subcommand, git.rest);
  if (bypass) return bypass;
  return gitSubcommands.get(git.subcommand)?.(git.rest, git.cwd) ?? null;
}

function expandHome(word) {
  if (word.quoted || !(word.text === "~" || word.text.startsWith("~/"))) return word.text;
  return join(homedir(), word.text.slice(1));
}

function hasUncommittedWork(paths, projectRoot) {
  const status = spawnSync(
    "git",
    ["--no-optional-locks", "status", "--porcelain", "--untracked-files=normal", "--", ...paths],
    { cwd: projectRoot, encoding: "utf8", timeout: 5000 },
  );
  return status.status !== 0 || status.stdout.trim() !== "";
}

function rmVerdict(args, { projectRoot, cwd }) {
  const { flags, operands, afterDashes } = parseArgs(args, NO_VALUE_FLAGS);
  const recursive = flags.includes("--recursive") || hasShort(flags, "r") || hasShort(flags, "R");
  if (!recursive) return null;
  const targets = [...operands, ...(afterDashes ?? [])]
    .filter((word) => !word.text.includes("$"))
    .map((word) => resolve(cwd, expandHome(word)));
  const gitDir = join(projectRoot, ".git");
  if (targets.some((target) => isWithin(projectRoot, target) || isWithin(target, gitDir))) {
    return ask(reasons.deletesProject);
  }
  const inside = targets
    .filter((target) => isWithin(target, projectRoot))
    .map((target) => relative(projectRoot, target));
  return inside.length > 0 && hasUncommittedWork(inside, projectRoot)
    ? ask(reasons.deletesWork)
    : null;
}

function packageManagerVerdict(args) {
  const action = args.find((word) => !isFlag(word))?.text;
  return PACKAGE_INSTALLS.has(action) ? deny(reasons.foreignPackageManager) : null;
}

function npxVerdict(args) {
  const tool = args.find((word) => !isFlag(word))?.text.replace(/(?<=.)@.*$/, "");
  return DOWNLOADED_TOOLS.has(tool) ? deny(reasons.downloadedTool) : null;
}

const programs = new Map([
  ["git", gitVerdict],
  ["rm", rmVerdict],
  ["pnpm", packageManagerVerdict],
  ["yarn", packageManagerVerdict],
  ["bun", packageManagerVerdict],
  ["npx", npxVerdict],
]);

function commandVerdict({ assignments, program, args }, location) {
  if (assignments.some(disablesHooks)) return deny(reasons.hooksDisabled);
  return programs.get(program)?.(args, location) ?? null;
}

export function bashVerdict(command, { projectRoot, cwd }) {
  const location = {
    projectRoot,
    cwd: cwd === undefined ? projectRoot : resolve(projectRoot, cwd),
  };
  let asked = null;
  for (const simpleCommand of simpleCommands(command)) {
    const verdict = commandVerdict(simpleCommand, location);
    if (verdict?.decision === "deny") return verdict;
    asked ??= verdict;
  }
  return asked;
}

function projectPath(filePath, projectRoot) {
  const absolute = isAbsolute(filePath) ? filePath : resolve(projectRoot, filePath);
  const path = relative(projectRoot, absolute).replaceAll("\\", "/");
  return path.startsWith("..") ? null : path;
}

function patchTargets(patch) {
  return [
    ...patch.matchAll(/^\*\*\* (?:Add|Update|Delete) File: (.+)$|^\*\*\* Move to: (.+)$/gm),
  ].map((match) => (match[1] ?? match[2]).trim());
}

function editTargets(toolName, toolInput) {
  if (toolName === "apply_patch" && typeof toolInput?.command === "string") {
    return patchTargets(toolInput.command);
  }
  if (["Edit", "Write", "MultiEdit", "NotebookEdit"].includes(toolName)) {
    const target = toolInput?.file_path ?? toolInput?.notebook_path;
    return typeof target === "string" ? [target] : [];
  }
  return [];
}

export function editVerdict(toolName, toolInput, { projectRoot }) {
  for (const target of editTargets(toolName, toolInput)) {
    const path = projectPath(target, projectRoot);
    if (path === null) continue;
    const hit = protectedPaths.find((rule) => rule.test(path, projectRoot));
    if (hit) return deny(hit.reason);
  }
  return null;
}
